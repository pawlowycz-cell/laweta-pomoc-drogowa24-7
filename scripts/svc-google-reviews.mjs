export function reviewsHtmlList(reviews) {
  return (reviews || [])
    .map((r) => {
      const stars = '&#9733;'.repeat(r.stars || 5);
      const name = String(r.name || '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/"/g, '&quot;');
      const text = String(r.text || '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/"/g, '&quot;');
      return (
        `<div style="background:var(--b4);border-radius:12px;padding:16px;">` +
        `<div style="display:flex;justify-content:space-between;margin-bottom:6px;">` +
        `<span style="font-weight:600;color:var(--w);font-size:.88rem;">${name}</span>` +
        `<span style="color:#fbbc04;">${stars}</span></div>` +
        `<p style="color:var(--gl);font-size:.84rem;line-height:1.65;margin:0;">${text}</p>` +
        `</div>`
      );
    })
    .join('');
}

